// Offline source generator; production loads only the checked-in Lua data.
// Node's Unicode property escapes provide the same categories as the former picker.
const sets = { control: /\p{C}/u, separator: /\p{Z}/u };
console.log(`-- Generated by tests/helpers/generate-rex-unicode.mjs; Unicode ${process.versions.unicode}.\nreturn {`);
for (const [name, pattern] of Object.entries(sets)) {
  const ranges = [];
  let start;
  for (let cp = 0; cp <= 0x110000; cp++) {
    const match = cp < 0x110000 && pattern.test(String.fromCodePoint(cp));
    if (match && start === undefined) start = cp;
    if (!match && start !== undefined) { ranges.push(start, cp - 1); start = undefined; }
  }
  console.log(`  ${name} = {`);
  for (let i = 0; i < ranges.length; i += 12) console.log(`    ${ranges.slice(i, i + 12).join(", ")},`);
  console.log("  },");
}
console.log("}");
